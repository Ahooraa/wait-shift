"""Heu: Xu et al., "Stateful serverless application placement in MEC with function and state dependencies", IEEE TC 72(9), 2023
(DOI 10.1109/TC.2023.3262947), Algorithm 1, adapted to the DFPS system model (BASELINES_SPEC.md, AB-H1..AB-H7).

Stages (paper Sec.4.1) -> code:
 1. state-placing DAG G'_f and 2. parallel schedule: the tasks of the workflow are split into sequential partition components
    A_{F,1..Q} of mutually independent tasks (topological levels = longest path from a root); all tasks of one component are
    consolidated into ONE node (`levels`).
 3. auxiliary graph G'(F): Q layers; a path chooses one node per layer. Edge weights (Eq.18-19 and the text below them):
      node edge <CL_{i,q}, CL'_{i,q}>  cost  sum_{f in A_q} M_i D_i c_l N_l  (+ storage term for the states of A_{q-1})
                                         delay max_{f in A_q} (alpha_i M_i N_l + d^o_{l,i})   (conservative: cold start always)
      network edges inside layer q       cost c_e (1+eta) per hop and per unit of state generated by A_{q-1}, delay d_e (1+eta)
      source v_j -> CL_{i,1}: zero (paper) -- here the real transfer of the request input (AB-H7)
    DFPS has no per-node cost/delay coefficients, so M_i, D_i, c_l, N_l, c_i, c_e, d_e, alpha_i are node independent (AB-H3):
    c_e = 1 per MB and hop, d_e = 1/bw s per MB and hop (this is exactly Eq.1-2 of the DFPS paper), processing cost = mu_l.
    The node-edge terms are then identical for every node, so the path cost only depends on the transfers (hops x MB).
 4. assign requests: here ONE request at a time as it arrives (online; the paper sorts a batch by data volume, AB-H4); prune the
    nodes that cannot hold the component (residual container slots and storage), find a delay-constrained least-cost path
    (layered dynamic programming; if the least-cost path violated the delay requirement the least-delay path is used, which is
    feasible by construction of d_req), and create the instances on demand (cold starts) on the chosen nodes."""
from __future__ import annotations

import numpy as np


class HeuPolicy:
    mode = "plan"
    name = "Heu"

    def __init__(self, seed=0, delay_slack=2.0):
        self.rng = np.random.default_rng(seed)
        self.delay_slack = delay_slack      # d_req_j = delay_slack x (least achievable delay of the conservative model), AB-H3
        self.n_prune_fail = 0
        self.n_delay_fallback = 0
        self._levels = {}

    def attach(self, sim):
        self.sim = sim

    # --- stages 1-2 ---------------------------------------------------------------------------------------------
    def levels(self, wf):
        """Partition components A_{F,q}: longest-path level of every task (computed once per workflow)."""
        if wf.id not in self._levels:
            lvl = [0] * wf.n
            for t in range(wf.n):                                    # tasks are in topological order
                if wf.parents[t]:
                    lvl[t] = 1 + max(lvl[p] for p in wf.parents[t])
            comps = [[t for t in range(wf.n) if lvl[t] == q] for q in range(max(lvl) + 1)]
            self._levels[wf.id] = (lvl, comps)
        return self._levels[wf.id]

    # --- stage 3-4 ----------------------------------------------------------------------------------------------
    def weights(self, sim, wf):
        """Per-layer transfer weight w_q = MB of state that must reach layer q (input for q=0, states generated by A_{q-1}),
        and the conservative node-edge delay of every layer."""
        _, comps = self.levels(wf)
        w = [wf.input_size]
        for q in range(1, len(comps)):
            w.append(float(sum(wf.ss[(u, v)] for u in comps[q - 1] for v in wf.children[u])))
        node_delay = [max(sim.exec_time[wf.ft[t]] + sim.cold_start[wf.ft[t]] for t in comp) for comp in comps]
        return w, node_delay

    def feasible(self, sim, wf):
        """Pruning (Alg.1 l.5): residual container slots and storage must meet the component's demand."""
        _, comps = self.levels(wf)
        resid = sim.ecc - sim.occ - np.array([len(q) for q in sim.nq])
        free_store = sim.esc - sim.storage_used
        feas = np.zeros((len(comps), sim.N), dtype=bool)
        for q, comp in enumerate(comps):
            need_slots = np.minimum(len(comp), sim.ecc)               # a component larger than a node runs in waves (AB-H1)
            feas[q] = (resid >= need_slots) & (free_store >= sum(wf.input_total(t) for t in comp))
        return feas

    def _path(self, sim, origin, w, feas, metric_w, jitter):
        """Least-weight layered path. metric_w[q]: weight per hop of the transfer into layer q. Returns (nodes, total)."""
        h = sim.net.h.astype(float)
        Q, N = len(w), sim.N
        cost = np.where(feas[0], h[origin] * metric_w[0], np.inf)
        back = []
        for q in range(1, Q):
            m = cost[:, None] + h * metric_w[q]
            if jitter:
                m = m + self.rng.random(m.shape) * 1e-9
            arg = m.argmin(axis=0)
            new = m[arg, np.arange(N)]
            new = np.where(feas[q], new, np.inf)
            back.append(arg)
            cost = new
        end = cost + (self.rng.random(N) * 1e-9 if jitter else 0.0)
        j = int(end.argmin())
        if not np.isfinite(cost[j]):
            return None, np.inf
        nodes = [j]
        for arg in reversed(back):
            nodes.append(int(arg[nodes[-1]]))
        nodes.reverse()
        return nodes, float(cost[j])

    def _delay(self, sim, origin, nodes, w, node_delay):
        h, bw = sim.net.h, sim.net.bw
        d, prev = 0.0, origin
        for q, j in enumerate(nodes):
            d += h[prev, j] * w[q] / bw + node_delay[q]
            prev = j
        return d

    def plan(self, sim, r):
        wf = r.wf
        lvl, comps = self.levels(wf)
        w, node_delay = self.weights(sim, wf)
        feas = self.feasible(sim, wf)
        if not feas.any(axis=1).all():
            self.n_prune_fail += 1
            return None
        # cost metric: c_e x MB per hop; delay metric: MB / bw per hop (proportional here, kept separate for the constraint)
        cost_w = w
        delay_w = [x / sim.net.bw for x in w]
        nodes, _ = self._path(sim, r.origin, w, feas, cost_w, jitter=True)
        if nodes is None:
            self.n_prune_fail += 1
            return None
        dmin_nodes, _ = self._path(sim, r.origin, w, feas, delay_w, jitter=False)
        d_req = self.delay_slack * self._delay(sim, r.origin, dmin_nodes, w, node_delay)
        if self._delay(sim, r.origin, nodes, w, node_delay) > d_req:     # delay-constrained: fall back to the least-delay path
            self.n_delay_fallback += 1
            nodes = dmin_nodes
        return [nodes[lvl[t]] for t in range(wf.n)]

    def on_task_done(self, sim, run):
        pass
